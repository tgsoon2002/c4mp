const ARCH = `// Generated by c4pm from a code snapshot. Edit freely: metadata you add is kept when you regenerate.
specification {
  element system
  element container
  element component
}

model {
  sample_shop = system 'sample-shop' {
    api = container 'Api' {
      technology 'Node.js / TypeScript'
    }
    web = container 'Web' {
      technology 'Node.js'
      metadata {
        status 'in-progress'
        owner 'kay'
      }
    }
  }
}
`;

const API = `// Generated by c4pm from a code snapshot.
model {
  extend sample_shop.api {
    lib = component 'Lib' {
      link ../api/src/lib/
    }
    // keep this comment
    routes = component 'Routes' {
      link ../api/src/routes/
      metadata {
        status 'done'
      }
    }
  }

  sample_shop.api.routes -> sample_shop.api.lib
}
`;

const SAME = `model {
  a = system 'A' {
    shared = container 'Shared A' {
      link ../a/
    }
  }
  b = system 'B' {
    shared = container 'Shared B' {
      link ../b/
    }
  }
}
`;

function sig(text: string) {
  const r = parseC4(text, 'x.c4');
  return { els: r.elements, rels: r.relations, issues: r.issues };
}

function roundTrip(text: string, fqn: string, key: string, value: string) {
  const before = sig(text);
  const res = setElementMetadata(text, fqn, key, value);
  const after = sig(res.text);
  expect(after.issues).toEqual(before.issues);
  const target = after.els.find(e => e.id === fqn)!;
  expect(target.metadata[key]).toBe(value);
  for (const e of before.els) {
    const a = after.els.find(x => x.id === e.id)!;
    if (e.id === fqn) {
      expect(a.links).toEqual(e.links);
      expect(a.metadata).toEqual({ ...e.metadata, [key]: value });
    } else {
      expect(a.metadata).toEqual(e.metadata);
      expect(a.links).toEqual(e.links);
    }
    expect(a.title).toBe(e.title);
    expect(a.technology).toBe(e.technology);
  }
  expect(after.els.length).toBe(before.els.length);
  expect(after.rels.map(r => [r.from, r.to, r.label])).toEqual(before.rels.map(r => [r.from, r.to, r.label]));
  return res;
}

describe('setElementMetadata', () => {
  it('adds a metadata block when absent, in the file indentation style', () => {
    const res = roundTrip(ARCH, 'sample_shop.api', 'layout', '1,2,3,4');
    expect(res.changed).toBe(true);
    expect(res.text).toContain(
      "    api = container 'Api' {\n      technology 'Node.js / TypeScript'\n      metadata {\n        layout '1,2,3,4'\n      }\n    }\n",
    );
  });

  it('appends the key to an existing block lacking it', () => {
    const res = roundTrip(ARCH, 'sample_shop.web', 'layout', '1,2,3,4');
    expect(res.text).toContain("        owner 'kay'\n        layout '1,2,3,4'\n      }");
  });

  it('replaces the value when the key exists; everything else is byte-identical', () => {
    const res = roundTrip(ARCH, 'sample_shop.web', 'status', 'done');
    expect(res.text).toBe(ARCH.replace("status 'in-progress'", "status 'done'"));
  });

  it('is idempotent: second call returns changed:false and same text', () => {
    const first = setElementMetadata(ARCH, 'sample_shop.api', 'layout', '1,2,3,4');
    const second = setElementMetadata(first.text, 'sample_shop.api', 'layout', '1,2,3,4');
    expect(second).toEqual({ text: first.text, changed: false });
    const third = setElementMetadata(first.text, 'sample_shop.api', 'layout', '9,9,9,9');
    expect(third.changed).toBe(true);
    expect(sig(third.text).els.find(e => e.id === 'sample_shop.api')!.metadata.layout).toBe('9,9,9,9');
  });

  it('edits an element inside an extend block, keeping comments and relations', () => {
    const res = roundTrip(API, 'sample_shop.api.lib', 'layout', '5,6,7,8');
    expect(res.text).toContain("    // keep this comment\n");
    const res2 = roundTrip(API, 'sample_shop.api.routes', 'layout', '5,6,7,8');
    expect(res2.text).toContain("        status 'done'\n        layout '5,6,7,8'\n");
  });

  it('two same-named elements under different parents: only the right one changes', () => {
    const res = roundTrip(SAME, 'b.shared', 'layout', '1,1,1,1');
    expect(res.text.indexOf("layout")).toBeGreaterThan(res.text.indexOf('Shared B'));
    expect(res.text.match(/layout/g)!.length).toBe(1);
    expect(sig(res.text).els.find(e => e.id === 'a.shared')!.metadata).toEqual({});
    const resA = roundTrip(SAME, 'a.shared', 'layout', '2,2,2,2');
    expect(resA.text.indexOf('layout')).toBeLessThan(resA.text.indexOf('Shared B'));
  });

  it('preserves CRLF', () => {
    const crlf = ARCH.replace(/\n/g, '\r\n');
    const a = setElementMetadata(crlf, 'sample_shop.api', 'layout', '1,2,3,4');
    expect(a.text.replace(/\r\n/g, '')).not.toMatch(/[\r\n]/);
    expect(a.text.split('\r\n').length - 1).toBe(crlf.split('\r\n').length - 1 + 3);
    const b = setElementMetadata(crlf, 'sample_shop.web', 'layout', '1,2,3,4');
    expect(b.text.replace(/\r\n/g, '')).not.toMatch(/[\r\n]/);
    expect(sig(b.text).els.find(e => e.id === 'sample_shop.web')!.metadata.layout).toBe('1,2,3,4');
  });

  it('follows tab indentation', () => {
    const tabs = ARCH.replace(/^( +)/gm, m => '\t'.repeat(m.length / 2));
    const res = roundTrip(tabs, 'sample_shop.api', 'layout', '1');
    expect(res.text).toContain("\t\t\tmetadata {\n\t\t\t\tlayout '1'\n\t\t\t}\n");
  });

  it('element not in file -> unchanged', () => {
    expect(setElementMetadata(ARCH, 'nope.x', 'layout', '1')).toEqual({ text: ARCH, changed: false });
    expect(setElementMetadata(ARCH, 'api', 'layout', '1')).toEqual({ text: ARCH, changed: false });
    expect(setElementMetadata('', 'a', 'layout', '1')).toEqual({ text: '', changed: false });
  });

  it('escapes quotes and backslashes so the real parser reads the value back', () => {
    expect(quoteC4String("it's a\\b")).toBe("'it\\'s a\\\\b'");
    roundTrip(ARCH, 'sample_shop.api', 'note', "it's a\\b and \"q\"");
  });

  it('handles bodiless, one-line and empty-block shapes', () => {
    const t = "model {\n  s = system 'S'\n  t = system 'T' { link ../t/ }\n  u = system 'U' {\n    metadata {\n    }\n  }\n}\n";
    roundTrip(t, 's', 'layout', '1');
    roundTrip(t, 't', 'layout', '1');
    roundTrip(t, 'u', 'layout', '1');
    const one = "model {\n  s = system 'S' { metadata { status 'x' } }\n}\n";
    roundTrip(one, 's', 'layout', '1');
    roundTrip(one, 's', 'status', 'y');
  });

  it('never throws on broken text, returns it unchanged', () => {
    for (const bad of ["model { a = system 'A' { metadata { status 'x", "model { a = system 'A", "}}{{", "model { a = system 'A' {\n"]) {
      const r = setElementMetadata(bad, 'a', 'layout', '1');
      expect(r.text === bad || r.changed).toBe(true);
    }
    expect(setElementMetadata("model { a = system 'A' { metadata { status 'x", 'a', 'layout', '1').changed).toBe(false);
  });

  it('rejects invalid arguments', () => {
    expect(() => setElementMetadata(ARCH, 'sample_shop.api', 'bad key', '1')).toThrow(/invalid metadata key/);
    expect(() => setElementMetadata(ARCH, 'sample_shop.api', 'k', 'a\nb')).toThrow(/line breaks/);
  });
});

describe('scanner parity with the real lexer', () => {
  const texts: string[] = [ARCH, API, SAME, "a 'it\\'s' \"d\\\\\" x.y->z /* c\n */ // l\n k=v w@rd {}"];
  const fx = path.join(__dirname, 'fixtures');
  const walk = (d: string) => fs.readdirSync(d, { withFileTypes: true }).forEach(e => {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p);
    else if (e.name.endsWith('.c4')) texts.push(fs.readFileSync(p, 'utf-8'));
  });
  walk(fx);
  it.each(texts.map((t, i) => [i, t] as const))('text #%i', (_i, t) => {
    const real = tokenize(t).tokens;
    const mine = _scanForTest(t).toks.map(({ type, value, line }) => ({ type, value, line }));
    expect(mine).toEqual(real);
  });
});

describe('removeElementMetadata', () => {
  const WITH = (eol: string, ind = '  ') => [
    'model {', `${ind}app = system 'App' {`, `${ind}${ind}metadata {`, `${ind}${ind}${ind}layout ';1,2,3,4'`,
    `${ind}${ind}${ind}owner 'k'`, `${ind}${ind}}`, `${ind}}`, '}', ''].join(eol);
  const ONLY = (eol: string, ind = '  ') => [
    'model {', `${ind}app = system 'App' {`, `${ind}${ind}technology 'x'`, `${ind}${ind}metadata {`,
    `${ind}${ind}${ind}layout ';1,2,3,4'`, `${ind}${ind}}`, `${ind}}`, '}', ''].join(eol);

  it('removes the entry and keeps other keys', () => {
    const r = removeElementMetadata(WITH('\n'), 'app', 'layout');
    expect(r.changed).toBe(true);
    expect(r.text).toBe(WITH('\n').replace("      layout ';1,2,3,4'\n", ''));
    expect(sig(r.text).els[0].metadata).toEqual({ owner: 'k' });
  });

  it('removes an emptied metadata block as whole lines, CRLF and tabs kept', () => {
    for (const [eol, ind] of [['\n', '  '], ['\r\n', '  '], ['\r\n', '\t']]) {
      const r = removeElementMetadata(ONLY(eol, ind), 'app', 'layout');
      expect(r.changed).toBe(true);
      expect(r.text).toBe(['model {', `${ind}app = system 'App' {`, `${ind}${ind}technology 'x'`, `${ind}}`, '}', ''].join(eol));
    }
    expect(removeElementMetadata(WITH('\r\n'), 'app', 'layout').text).not.toMatch(/[^\r]\n/);
  });

  it('removes every entry of the key, also across blocks and inline', () => {
    const t = "model {\n  app = system 'App' {\n    metadata { layout ';1,1,1,1' owner 'k' }\n    metadata {\n      layout ';2,2,2,2'\n    }\n  }\n}\n";
    const r = removeElementMetadata(t, 'app', 'layout');
    expect(r.text).toBe("model {\n  app = system 'App' {\n    metadata { owner 'k' }\n  }\n}\n");
    expect(sig(r.text).els[0].metadata).toEqual({ owner: 'k' });
  });

  it('absent key, unknown element and second call are unchanged', () => {
    expect(removeElementMetadata(WITH('\n'), 'app', 'status')).toEqual({ text: WITH('\n'), changed: false });
    expect(removeElementMetadata(WITH('\n'), 'nope', 'layout').changed).toBe(false);
    const once = removeElementMetadata(ONLY('\n'), 'app', 'layout');
    expect(removeElementMetadata(once.text, 'app', 'layout')).toEqual({ text: once.text, changed: false });
    expect(() => removeElementMetadata(ARCH, 'a', 'bad key')).toThrow(/invalid metadata key/);
  });
});

// b721: editMetadataBatch gives byte for byte what the single edits give applied one by one, in one pass.
describe('editMetadataBatch', () => {
  /** The reference: the single edits one by one in order; a throw = that edit refused, the text kept. */
  function oneByOne(text: string, edits: MetaEdit[]) {
    const results: boolean[] = [];
    const errors: (string | null)[] = [];
    for (const e of edits) {
      try {
        const r = e.value === null ? removeElementMetadata(text, e.fqn, e.key) : setElementMetadata(text, e.fqn, e.key, e.value);
        results.push(r.changed);
        errors.push(null);
        text = r.text;
      } catch (err) {
        results.push(false);
        errors.push((err as Error).message);
      }
    }
    return { text, results, errors };
  }

  const INLINE = [
    'model {',
    "  s = system 'S' { a = container 'A' { } b = container 'B' { metadata { x 'y' } } c = container 'C' { technology 'T' } d = container 'D'}",
    "  e = system 'E' {",
    "    f = container 'F' { g = component 'G' }",
    "    h = component 'H'",
    "    i = component 'I' { metadata { uid 'old' type 'x' } metadata { type 'y' } }",
    '  }',
    '}',
    '',
  ].join('\n');
  const NOBODY = "model {\n  a = system 'A'\n  b = system 'B' 'desc'\n  extend a {\n    k = container 'K'\n  }\n}";
  const ONE_LINE = "model { x = system 'X' { y = container 'Y' } z = system 'Z' }";
  const STORAGE = fs.readFileSync(path.join(__dirname, 'fixtures', 'editmeta-batch', 'storage.c4'), 'utf8');
  const TEXTS: [string, string][] = [
    ['nested', ARCH],
    ['extend', API],
    ['crlf', ARCH.replace(/\n/g, '\r\n')],
    ['tabs', ARCH.replace(/^( +)/gm, m => '\t'.repeat(m.length / 2))],
    ['inline bodies', INLINE],
    ['no body, no last line break', NOBODY],
    ['one line', ONE_LINE],
    ['storage.c4', STORAGE],
  ];
  const fqns = (text: string) => parseC4(text, 'x.c4').elements.map(e => e.id);

  const EDITS: [string, (ids: string[]) => MetaEdit[]][] = [
    ['set a new key on every element', ids => ids.map((fqn, i) => ({ fqn, key: 'owner', value: `o${i}` }))],
    ['set uid on every element (add and replace)', ids => ids.map((fqn, i) => ({ fqn, key: 'uid', value: `u'${i}\\` }))],
    ['set the value it already has', ids => ids.map(fqn => ({ fqn, key: 'type', value: 'string' }))],
    ['remove a key from every element', ids => ids.map(fqn => ({ fqn, key: 'uid', value: null }))],
    ['remove a key that shares its block', ids => ids.map(fqn => ({ fqn, key: 'type', value: null }))],
    ['mixed, children before parents', ids => [...ids].reverse().map((fqn, i): MetaEdit => (
      [
        { fqn, key: 'uid', value: `m${i}` }, { fqn, key: 'uid', value: null },
        { fqn, key: 'layout', value: ';1,2,3,4' }, { fqn, key: 'status', value: null },
      ][i % 4]
    ))],
    ['same element twice, unknown element, refused edits', ids => [
      { fqn: ids[0], key: 'layout', value: 'a' }, { fqn: 'no.such', key: 'layout', value: 'b' },
      { fqn: ids[1] ?? ids[0], key: 'bad key', value: 'c' }, { fqn: ids[ids.length - 1], key: 'note', value: 'x\ny' },
      { fqn: ids[ids.length - 1], key: 'layout', value: 'd' }, { fqn: ids[0], key: 'layout', value: null },
    ]],
  ];

  // Texts where a child's splice meets its parent's (`'D'}`, one-line nesting): those batches may go one by one.
  const MAY_MEET = new Set(['inline bodies', 'one line']);
  for (const [textName, text] of TEXTS) {
    it.each(EDITS)(`${textName}: %s`, (name, make) => {
      const edits = make(fqns(text));
      expect(edits.length).toBeGreaterThan(0);
      const spy = jest.spyOn(logMod, 'log');
      const batch = editMetadataBatch(text, edits);
      const oneByOneUsed = spy.mock.calls.some(c => c[1] === 'batch applied one by one');
      spy.mockRestore();
      const ref = oneByOne(text, edits);
      expect(batch.text).toBe(ref.text);
      expect(batch.results).toEqual(ref.results);
      expect(batch.errors).toEqual(ref.errors);
      if (name.startsWith('same element twice')) expect(oneByOneUsed).toBe(true);
      else if (!MAY_MEET.has(textName)) expect(oneByOneUsed).toBe(false); // the one-pass path is what is compared
    });
  }

  it('parent and child: both get their key, the rest of the plan unchanged', () => {
    const edits = fqns(ARCH).map(fqn => ({ fqn, key: 'uid', value: `id-${fqn}` }));
    const r = editMetadataBatch(ARCH, edits);
    expect(r.results.every(Boolean)).toBe(true);
    const after = parseC4(r.text, 'x.c4');
    expect(after.issues).toEqual(parseC4(ARCH, 'x.c4').issues);
    for (const e of after.elements) expect(e.metadata.uid).toBe(`id-${e.id}`);
  });

  it('unterminated string: text unchanged, every result false, refused edits still named', () => {
    const broken = "model {\n  a = system 'A\n}\n";
    const r = editMetadataBatch(broken, [{ fqn: 'a', key: 'uid', value: 'x' }, { fqn: 'a', key: 'bad key', value: 'y' }]);
    expect(r).toEqual({ text: broken, results: [false, false], errors: [null, 'invalid metadata key: "bad key"'] });
  });

  it('perf guard: a uid on each of 3000 elements in one pass', () => {
    const lines = ['model {', "  s = system 'S' {"];
    for (let i = 0; i < 3000; i++) {
      lines.push(`    c${i} = component 'Component ${i}' {`, "      description 'lorem ipsum'");
      if (i % 2) lines.push('      metadata {', "        status 'planned'", '      }');
      lines.push('    }');
    }
    lines.push('  }', '}', '');
    const text = lines.join('\n');
    const edits = Array.from({ length: 3000 }, (_, i) => ({ fqn: `s.c${i}`, key: 'uid', value: `uid-${i}` }));
    const t0 = Date.now();
    const r = editMetadataBatch(text, edits);
    const ms = Date.now() - t0;
    expect(r.results.every(Boolean)).toBe(true);
    expect(r.text.match(/uid 'uid-/g)).toHaveLength(3000);
    expect(ms).toBeLessThan(2000);
  });
});

describe('wholeLineSplice', () => {
  it('a token alone on its line takes the line break; a token sharing a line takes the blanks before it', () => {
    const t = 'a {\n  link x\n  k v  link y\n}\n';
    const cur = textCursor(t);
    const x = t.indexOf('link x');
    expect(wholeLineSplice(t, cur, x, x + 6)).toEqual({ at: 4, del: 9, ins: '' });
    const y = t.indexOf('link y');
    expect(wholeLineSplice(t, cur, y, y + 6)).toEqual({ at: y - 2, del: 8, ins: '' });
  });
});
