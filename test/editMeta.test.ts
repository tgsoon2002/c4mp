import * as path from 'path';
import {
  setElementMetadata, removeElementMetadata, quoteC4String, _scanForTest, editMetadataBatch, wholeLineSplice, type MetaEdit,
} from '../src/c4/editMeta';
import { textCursor } from '../src/c4/textEdit';
import * as logMod from '../src/log';
