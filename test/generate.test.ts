    const routes = comp('routes', 102, '../api/src/routes/').replace(/ {6}}\n$/, planned + '      }\n');
    const entry = layer('entry', 101, note + routes + comp('root_files', 103, '../api/src/server.ts'));
    const core = layer('core', 104, comp('services', 105, '../api/src/services/') + comp('extra', 106, '../api/src/extra/'));
    const rel = '  sample_shop.api.entry.routes -> sample_shop.api.core.services\n';
    const flat = comp('lib', 107, '../api/src/lib/', '    ') + comp('models', 108, '../api/src/models/', '    ');
